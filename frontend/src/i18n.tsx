export type Translate = (key: TranslationKey, vars?: Record<string, string | number>) => string;

interface I18nContextValue {
  language: Language;
  locale: string;
  t: Translate;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
}

function detectLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === 'zh' || stored === 'en') return stored;
  return window.navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`,
  );
}

const fallbackT: Translate = (key, vars) => interpolate(en[key] ?? key, vars);

const fallbackContext: I18nContextValue = {
  language: 'en',
  locale: 'en-GB',
  t: fallbackT,
  setLanguage: () => undefined,
  toggleLanguage: () => undefined,
};

const I18nContext = createContext<I18nContextValue>(fallbackContext);

export function I18nProvider({
  children,
  initialLanguage,
}: {
  children: ReactNode;
  initialLanguage?: Language;
}) {
  const [language, setLanguageState] = useState<Language>(
    () => initialLanguage ?? detectLanguage(),
  );
  const locale = language === 'zh' ? 'zh-CN' : 'en-GB';

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // Private browsing may block storage; the in-memory choice still applies.
    }
  }, []);

  const toggleLanguage = useCallback(() => {
    setLanguage(language === 'en' ? 'zh' : 'en');
  }, [language, setLanguage]);

  const t = useCallback<Translate>(
    (key, vars) => interpolate(dictionaries[language][key] ?? en[key] ?? key, vars),
    [language],
  );

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dataset.language = language;
  }, [language, locale]);

  const value = useMemo(
    () => ({ language, locale, t, setLanguage, toggleLanguage }),
    [language, locale, t, setLanguage, toggleLanguage],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

export function useErrorMessage() {
  const { language, t } = useI18n();
  return useCallback(
    (error: unknown): string => {
      if (language === 'zh' && error instanceof ApiError) {
        const key = API_ERROR_KEYS[error.code];
        if (key) return t(key);
      }
      if (error instanceof Error) return error.message;
      if (typeof error === 'string') return error;
      return t('error.internal_error');
    },
    [language, t],
  );
}
